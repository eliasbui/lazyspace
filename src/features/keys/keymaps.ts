const PUNCT: Readonly<Record<string, string>> = {
  Period: '.',
  Comma: ',',
  BracketLeft: '[',
  BracketRight: ']',
  Slash: '/',
  Backslash: '\\',
  Minus: '-',
  Equal: '=',
  Semicolon: ';',
  Quote: "'",
  Backquote: '`',
};

/**
 * The chord of a key event: modifiers in a fixed order, then the key by its place on the keyboard, so Shift+. is not
 * read as ">" and a Vietnamese layout gives the same chords.
 */
export function chord(e: Pick<KeyboardEvent, 'code' | 'key' | 'metaKey' | 'ctrlKey' | 'altKey' | 'shiftKey'>): string {
  let key = e.code.startsWith('Key') ? e.code.slice(3) : e.code.startsWith('Digit') ? e.code.slice(5) : (PUNCT[e.code] ?? e.key);
  if (key === ' ') key = 'Space';
  return `${e.metaKey ? 'Cmd+' : ''}${e.ctrlKey ? 'Ctrl+' : ''}${e.altKey ? 'Alt+' : ''}${e.shiftKey ? 'Shift+' : ''}${key}`;
}
